package io.github.strawberrymc;

import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.event.AddPackFindersEvent;

// The Ocean Monument puzzle jigsaws (template pools, pieces and the p2_test structure) live in their own always-on
// datapack (src/main/resources/monument_puzzles) so MCreator can't overwrite them. The pools and placeholder pieces are
// generated by tools/monument_puzzles/gen.py, and pieces built in game are copied in by tools/monument_puzzles/import.py.
public class MonumentPuzzlesPack {
	public static void init(IEventBus eventBus) {
		eventBus.addListener(MonumentPuzzlesPack::addPack);
	}

	private static void addPack(AddPackFindersEvent event) {
		event.addPackFinders(Identifier.fromNamespaceAndPath("strawberrymc", "monument_puzzles"), PackType.SERVER_DATA,
				Component.literal("Strawberry MC monument puzzles"), PackSource.BUILT_IN, true, Pack.Position.TOP);
	}
}
